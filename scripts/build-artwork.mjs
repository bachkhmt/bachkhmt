import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = new URL('../', import.meta.url);
const prompts = JSON.parse(await readFile(new URL('assets/artwork/prompts.json', root), 'utf8'));
const assets = [];
await mkdir(new URL('src/artwork/png/', root), { recursive: true });
for (const item of prompts.assets) {
  const input = new URL(item.file, root);
  const metadata = await sharp(fileURLToPath(input)).metadata();
  if (!metadata.hasAlpha) throw new Error(`Artwork must retain transparent alpha: ${item.file}`);
  const stats = await sharp(fileURLToPath(input)).stats();
  if (stats.channels[3].min !== 0)
    throw new Error(`Artwork has no fully transparent pixels: ${item.file}`);
  const name = `${item.character}-${item.pose}.png`;
  const { data, info } = await sharp(fileURLToPath(input))
    .resize({ width: 480, height: 560, fit: 'inside', withoutEnlargement: true })
    .png({ palette: true, colours: 128, dither: 0.3, compressionLevel: 9 })
    .toBuffer({ resolveWithObject: true });
  if (data.byteLength > 160 * 1024) throw new Error(`${name} exceeds the optimized asset budget`);
  await writeFile(new URL(`src/artwork/png/${name}`, root), data);
  assets.push({
    character: item.character,
    pose: item.pose,
    width: info.width,
    height: info.height,
    dataUri: `data:image/png;base64,${data.toString('base64')}`,
  });
  console.log(
    `${name}: ${info.width}×${info.height}, ${(data.length / 1024).toFixed(1)} KiB, alpha verified`,
  );
}
if (assets.length !== 24 || new Set(assets.map((a) => `${a.character}:${a.pose}`)).size !== 24)
  throw new Error('Expected 24 unique original artworks');
const characters = [...new Set(assets.map((asset) => asset.character))];
await mkdir(new URL('src/artwork/generated/', root), { recursive: true });
for (const character of characters)
  await writeFile(
    new URL(`src/artwork/generated/${character}.ts`, root),
    `// Generated by scripts/build-artwork.mjs.\nexport default ${JSON.stringify(assets.filter((asset) => asset.character === character))} as const;\n`,
  );
await writeFile(
  new URL('src/artwork/generated.ts', root),
  '// Offline aggregate for tooling and tests.\n' +
    characters
      .map((character) => `import ${character} from './generated/${character}';`)
      .join('\n') +
    `\nexport const ARTWORK = [${characters.map((character) => '...' + character).join(',')}] as const;\n`,
);
